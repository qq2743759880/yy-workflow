class LoginThrottler:
    """Per-client-IP bounded failure delay; process-level, not a full IAM."""

    def __init__(
        self,
        threshold: int = THROTTLE_THRESHOLD,
        delay: float = THROTTLE_DELAY_SECONDS,
        clock: Any = time.time,
        max_entries: int = 4096,
    ) -> None:
        self._threshold = threshold
        self._delay = delay
        self._clock = clock
        self._max_entries = max_entries
        self._failures: dict[str, int] = {}
        self._blocked_until: dict[str, float] = {}

    def retry_after(self, client_ip: str) -> float:
        """Seconds the client must still wait; 0 means the attempt is allowed."""
        blocked = self._blocked_until.get(client_ip, 0.0)
        return max(0.0, blocked - self._clock())

    def record_failure(self, client_ip: str) -> None:
        count = self._failures.get(client_ip, 0) + 1
        self._failures[client_ip] = count
        if count >= self._threshold:
            self._blocked_until[client_ip] = self._clock() + self._delay
        while len(self._failures) > self._max_entries:
            self._failures.pop(next(iter(self._failures)))

    def record_success(self, client_ip: str) -> None:
        self._failures.pop(client_ip, None)
        self._blocked_until.pop(client_ip, None)

    def reset(self) -> None:
        self._failures.clear()
        self._blocked_until.clear()


_throttler = LoginThrottler()


def configure_auth(secret: str | None, password_hash: str | None, issuer: str | None = None) -> None:
    """Install the signing secret, PBKDF2 password hash, and public issuer."""
    global _auth_secret, _auth_password_hash, _auth_issuer
    if not secret or len(secret) < REQUIRED_SECRET_CHARS:
        raise ValueError("YY_AUTH_SECRET must be at least 32 characters.")
    if _parse_password_hash(password_hash or "") is None:
        raise ValueError(
            "YY_AUTH_PASSWORD_HASH must be a pbkdf2_sha256 encoding from auth.hash_password()."
        )
    _auth_secret = secret
    _auth_password_hash = password_hash
    _auth_issuer = (issuer or "").rstrip("/") or None
    _throttler.reset()


def reset_auth() -> None:
    """Clear configuration and in-flight codes (test isolation only)."""
    global _auth_secret, _auth_password_hash, _auth_issuer
    _auth_secret = None
    _auth_password_hash = None
    _auth_issuer = None
    _throttler.reset()


def normalize_scope(value: Any) -> str:
    """Map any scope value onto the two-level lattice; unknown means synthetic."""
    scopes = value.split() if isinstance(value, str) else []
    return PRODUCTION_SCOPE if PRODUCTION_SCOPE in scopes and all(
        scope in SUPPORTED_SCOPES for scope in scopes
    ) else SYNTHETIC_SCOPE


# --- Credential hardening (PBKDF2-HMAC-SHA256) ---
def hash_password(password: str, *, iterations: int = PBKDF2_ITERATIONS, salt: bytes | None = None) -> str:
    """Encode a password as pbkdf2_sha256$<iters>$<salt>$<digest> (base64)."""
    if iterations < 1:
        raise ValueError("iterations must be positive")
    salt = salt or secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, iterations)
    return "$".join((
        PASSWORD_HASH_PREFIX,
        str(iterations),
        base64.b64encode(salt).decode("ascii"),
        base64.b64encode(digest).decode("ascii"),
    ))


def _parse_password_hash(encoded: str) -> tuple[bytes, int, bytes] | None:
    """Return (salt, iterations, expected_digest) for a stored hash; else None."""
    parts = (encoded or "").strip().split("$")
    if len(parts) != 4 or parts[0] != PASSWORD_HASH_PREFIX:
        return None
    try:
        iterations = int(parts[1])
        salt = base64.b64decode(parts[2], validate=True)
        digest = base64.b64decode(parts[3], validate=True)
    except (ValueError, TypeError):
        return None
    if iterations < 1 or not salt or not digest:
        return None
    return salt, iterations, digest


def verify_password(password: str) -> bool:
    """Constant-time PBKDF2 verification against the configured hash."""
    parsed = _parse_password_hash(_auth_password_hash or "")
    if parsed is None:
        return False
    salt, iterations, expected = parsed
    actual = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, iterations)
    return hmac.compare_digest(actual, expected)


def _client_ip(request: Request) -> str:
    return request.client.host if request.client else "unknown"


# --- Caller scope resolution (request-scoped only; no shared global state) ---
def current_caller_scope() -> str:
    """Scope of the current MCP request; synthetic unless its token says otherwise.

    Claims come exclusively from the current ASGI/MCP request context, so
    concurrent requests can never observe each other's authorization.
    """
    try:
        from fastmcp.server.dependencies import get_http_request
        claims = get_http_request().scope.get(CLAIMS_SCOPE_KEY)
    except Exception:
        claims = None
    if isinstance(claims, dict):
        return normalize_scope(claims.get("scope"))
    return SYNTHETIC_SCOPE


def _bearer_token_from_scope(scope: dict) -> tuple[bool, str | None]:
    """Return (header_present, bearer_token_or_None) from raw ASGI headers."""
    for name, value in scope.get("headers") or []:
        if name.lower() != b"authorization":
            continue
        scheme, _, token = value.decode("latin-1").strip().partition(" ")
        if scheme.lower() != "bearer":
            return True, None
        return True, token.strip() or None
    return False, None


class BearerChallengeMiddleware:
    """Anonymous-allowed, invalid-bearer fail-closed ASGI middleware (RFC 6750).

    On MCP resource paths, a missing Authorization header means anonymous
    synthetic access. Any present header must carry a token that verifies (signature, issuer,
    audience, expiry, supported scopes); otherwise the request is rejected with
    401 and a ``WWW-Authenticate`` challenge pointing at the RFC 9728 metadata.
    Authorization server routes keep the SDK's client authentication policy.
    """

    def __init__(self, app: Any, verifier: Any, resource_metadata_url: str) -> None:
        self.app = app
        self.verifier = verifier
        self.resource_metadata_url = resource_metadata_url

    async def __call__(self, scope: dict, receive: Any, send: Any) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return
        path = scope.get("path", "")
        if not any(path == resource or path.startswith(resource + "/") for resource in MCP_RESOURCE_PATHS):
            await self.app(scope, receive, send)
            return
        header_present, token = _bearer_token_from_scope(scope)
        if not header_present:
            scope[CLAIMS_SCOPE_KEY] = None
            await self.app(scope, receive, send)
            return
        if token is None:
            await self._reject(send, "invalid_request", "Bearer authentication is required.")
            return
        access_token = await self.verifier.verify_token(token)
        if access_token is None or not self._scopes_supported(access_token):
            await self._reject(send, "invalid_token", "Access token is invalid, expired, or has unknown scopes.")
            return
        claims = dict(access_token.claims or {})
        claims["scope"] = " ".join(access_token.scopes)
        scope[CLAIMS_SCOPE_KEY] = claims
        await self.app(scope, receive, send)

    @staticmethod
    def _scopes_supported(access_token: AccessToken) -> bool:
        scopes = access_token.scopes or []
        return bool(scopes) and all(scope in SUPPORTED_SCOPES for scope in scopes)

    async def _reject(self, send: Any, error: str, description: str) -> None:
        www_authenticate = ", ".join((
            f"Bearer error=\"{error}\"",
            f"error_description=\"{description}\"",
            f"resource_metadata=\"{self.resource_metadata_url}\"",
        ))
        body = json.dumps({"error": error, "error_description": description}).encode("utf-8")
        await send({
            "type": "http.response.start",
            "status": 401,
            "headers": [
                (b"content-type", b"application/json"),
                (b"content-length", str(len(body)).encode("ascii")),
                (b"www-authenticate", www_authenticate.encode("utf-8")),
            ],
        })
        await send({"type": "http.response.body", "body": body})


# --- Authorization server provider (SDK protocol hooks) ---
class YYTokenVerifier(JWTVerifier):
    """HS256 JWT verifier bound to the YY issuer and canonical resource audience.

    ``verify_token`` (inherited) checks signature, ``iss``, ``aud == canonical
    YY MCP resource``, ``exp``, and scopes, returning an ``AccessToken`` or
    ``None``; ``None`` makes the bearer middleware fail closed with 401.
    """

    def __init__(self, *, signing_key: bytes, issuer: str, resource: str) -> None:
        super().__init__(public_key=signing_key, algorithm="HS256", issuer=issuer, audience=resource)


class YYAuthorizationServerProvider(OAuthAuthorizationServerProvider):
    """YY authorization hooks over the SDK protocol; CIMD-resolved clients.

    The SDK handlers own request validation, PKCE, redirect binding at /token,
    and client authentication. This provider owns the owner login, the
    single-use authorization-code store (with the RFC 8707 ``resource``
    binding), and JWT minting for ``exchange_authorization_code``.
    """

    def __init__(
        self,
        client_manager: CIMDClientManager,
        token_issuer: JWTIssuer,
        verifier: YYTokenVerifier,
        resource: str,
    ) -> None:
        self.client_manager = client_manager
        self.token_issuer = token_issuer
        self.verifier = verifier
        self.resource = resource
        self._clients: dict[str, OAuthClientInformationFull] = {}
        self._authorization_codes: dict[str, AuthorizationCode] = {}

    # -- client resolution: process registry first, then CIMD discovery --
    async def get_client(self, client_id: str) -> OAuthClientInformationFull | None:
        key = str(client_id).rstrip("/")
        client = self._clients.get(key)
        if client is not None:
            return client
        if self.client_manager.is_cimd_client_id(str(client_id)):
            client = await self.client_manager.get_client(str(client_id))
            if client is not None:
                self._clients[key] = client
            return client
        return None

    async def register_client(self, client_info: OAuthClientInformationFull) -> None:
        """Dynamic registration (RFC 7591): persist the SDK-issued client."""
        self._clients[str(client_info.client_id).rstrip("/")] = client_info

    def seed_cimd_document(self, document: CIMDDocument) -> str:
        """Register a CIMD document without network fetch (deploy seeds/tests).

        Builds exactly the synthetic client ``CIMDClientManager.get_client``
        builds after a successful document fetch.
        """
        from fastmcp.server.auth.oauth_proxy.models import ProxyDCRClient

        client = ProxyDCRClient(
            client_id=str(document.client_id),
            client_secret=None,
            redirect_uris=None,
            grant_types=document.grant_types,
            scope=document.scope or self.client_manager.default_scope,
            token_endpoint_auth_method=document.token_endpoint_auth_method,
            allowed_redirect_uri_patterns=self.client_manager.allowed_redirect_uri_patterns,
            client_name=document.client_name,
            cimd_document=document,
            cimd_fetched_at=time.time(),
        )
        self._clients[str(document.client_id).rstrip("/")] = client
        return str(document.client_id)

    # -- authorization endpoint hook: hand off to the owner login form --
    async def authorize(self, client: OAuthClientInformationFull, params: AuthorizationParams) -> str:
        query = urllib.parse.urlencode({
            "response_type": "code",
            "client_id": str(client.client_id),
            "redirect_uri": str(params.redirect_uri),
            "state": params.state or "",
            "code_challenge": params.code_challenge,
            "code_challenge_method": "S256",
            "scope": " ".join(params.scopes or []) ,
            "resource": params.resource or "",
        })
        return f"{LOGIN_PATH}?{query}"

    # -- single-use code store with resource binding --
    def issue_authorization_code(
        self,
        client: OAuthClientInformationFull,
        redirect_uri: AnyUrl,
        code_challenge: str,
        scopes: list[str],
        resource: str | None,
    ) -> AuthorizationCode:
        self._purge_expired_codes()
        code = AuthorizationCode(
            code=secrets.token_urlsafe(32),
            scopes=scopes,
            expires_at=time.time() + AUTHORIZATION_CODE_TTL_SECONDS,
            client_id=str(client.client_id),
            code_challenge=code_challenge,
            redirect_uri=redirect_uri,
            redirect_uri_provided_explicitly=True,
            resource=resource,
            subject=OWNER_SUBJECT,
        )
        self._authorization_codes[code.code] = code
        return code

    async def load_authorization_code(
        self, client: OAuthClientInformationFull, authorization_code: str
    ) -> AuthorizationCode | None:
        record = self._authorization_codes.pop(str(authorization_code), None)  # single use
        if record is None or record.expires_at < time.time():
            return None
        return record

    async def exchange_authorization_code(
        self, client: OAuthClientInformationFull, authorization_code: AuthorizationCode
    ) -> OAuthToken:
        scopes = list(authorization_code.scopes or [PRODUCTION_SCOPE])
        token = self.token_issuer.issue_access_token(
            client_id=str(client.client_id),
            scopes=scopes,
            jti=secrets.token_hex(16),
            expires_in=ACCESS_TOKEN_TTL_SECONDS,
            subject=authorization_code.subject or OWNER_SUBJECT,
        )
        return OAuthToken(
            access_token=token,
            token_type="Bearer",
            expires_in=ACCESS_TOKEN_TTL_SECONDS,
            scope=" ".join(scopes),
        )

    async def load_access_token(self, token: str) -> AccessToken | None:
        """Resource-server side of the same provider: JWT verification."""
        return await self.verifier.verify_token(token)

    def _purge_expired_codes(self) -> None:
        now = time.time()
        for key in [key for key, code in self._authorization_codes.items() if code.expires_at <= now]:
            del self._authorization_codes[key]

    def token_request_resource_matches(self, code: str, resource: str | None) -> bool:
        """RFC 8707: the /token resource must equal the authorization-time one."""
        record = self._authorization_codes.get(str(code))
        if record is None:
            return True  # unknown codes are rejected by the SDK token handler
        return _normalize_resource(record.resource, self.resource) == _normalize_resource(resource, self.resource)


def _normalize_resource(value: str | None, canonical: str) -> str:
    return (value or canonical).strip().rstrip("/") or canonical.rstrip("/")


