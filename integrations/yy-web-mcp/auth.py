"""OAuth 2.1 production access boundary built from MCP/FastMCP SDK primitives.

No OAuth protocol code is hand-written here. The protocol surface comes from the
SDK: ``mcp.server.auth.routes.create_auth_routes`` serves RFC 8414 discovery,
``/authorize`` (request validation + redirect) and ``/token`` (client
authentication, PKCE S256 verification, redirect binding); dynamic client
registration is ``/register``; ``fastmcp.server.auth.cimd.CIMDClientManager``
resolves ChatGPT-style URL client identities (CIMD); redirect URIs are checked
with ``fastmcp.server.auth.redirect_validation.validate_redirect_uri`` against
the CIMD document's allowlist; tokens are minted with
``fastmcp.server.auth.jwt_issuer.JWTIssuer`` (iss/aud/sub/scope/iat/exp/jti) and
verified by ``fastmcp.server.auth.providers.jwt.JWTVerifier``; RFC 9728
protected-resource metadata is generated by
``fastmcp.server.auth.RemoteAuthProvider``.

This module only supplies the YY-specific glue: the authorization provider hooks
(owner login + single-use code store), the RFC 8707 ``resource`` binding across
the authorize/exchange chain, the anonymous-allowed / invalid-bearer-fail-closed
ASGI policy, per-request caller-scope resolution, and credential hardening
(PBKDF2-HMAC-SHA256 + constant-time compare + per-IP login throttling).
"""
