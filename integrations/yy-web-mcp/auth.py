_LOGIN_PAGE = """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>YY Web MCP sign-in</title></head>
<body style="font-family:sans-serif;max-width:24rem;margin:4rem auto"><h2>YY Web MCP</h2>
<p>Owner sign-in is required to unlock production workflow bindings.</p>{error}
<form method="post" action="/login">{hidden}
<label>Password <input type="password" name="password" autofocus required></label>
<button type="submit">Sign in</button></form></body></html>"""


def render_login_form(params: dict[str, str], error: str | None = None) -> str:
    hidden = "".join(
        f'<input type="hidden" name="{html.escape(name)}" value="{html.escape(params.get(name, ""))}">'
        for name in LOGIN_FORM_FIELDS
    )
    banner = f'<p style="color:#b00020">{html.escape(error)}</p>' if error else ""
    return _LOGIN_PAGE.format(error=banner, hidden=hidden)


def _redirect_patterns(client: OAuthClientInformationFull) -> list[str]:
    """Exact allowlist: CIMD document redirect_uris, else registered ones."""
    document = getattr(client, "cimd_document", None)
    source = document.redirect_uris if document is not None and document.redirect_uris else client.redirect_uris
    return [str(uri) for uri in (source or [])]


class LoginRequestError(Exception):
    def __init__(self, error: str, description: str) -> None:
        super().__init__(description)
        self.error = error
        self.description = description


async def validate_login_request(provider: YYAuthorizationServerProvider, params: dict[str, str]):
    """Re-validate the preserved authorization request behind the login form."""
    if params.get("response_type") != "code":
        raise LoginRequestError("unsupported_response_type", "response_type must be 'code'.")
    if params.get("code_challenge_method") != "S256":
        raise LoginRequestError("invalid_request", "code_challenge_method must be S256.")
    challenge = params.get("code_challenge", "")
    if not 43 <= len(challenge) <= 128:
        raise LoginRequestError("invalid_request", "code_challenge must be 43-128 characters.")
    client = await provider.get_client(params.get("client_id", ""))
    if client is None:
        raise LoginRequestError("invalid_request", f"Client ID '{params.get('client_id', '')}' not found.")
    try:
        redirect_uri = AnyUrl(params.get("redirect_uri", ""))
    except ValidationError as validation_error:
        raise LoginRequestError("invalid_request", "redirect_uri is not a valid URI.") from validation_error
    if not validate_redirect_uri(str(redirect_uri), _redirect_patterns(client)):
        raise LoginRequestError(
            "invalid_request",
            f"Redirect URI '{redirect_uri}' is not on the client allowlist.",
        )
    requested = (params.get("scope") or "").split()
    granted = [scope for scope in requested if scope in SUPPORTED_SCOPES]
    if requested and len(granted) != len(requested):
        raise LoginRequestError("invalid_scope", "Requested scope is not supported.")
    if not granted:
        granted = [PRODUCTION_SCOPE]  # single-owner server: login grants production
    resource = params.get("resource") or None
    if resource is not None and _normalize_resource(resource, provider.resource) != _normalize_resource(None, provider.resource):
        raise LoginRequestError("invalid_target", "resource must be this MCP server.")
    return client, redirect_uri, challenge, granted, resource


def build_login_routes(provider: YYAuthorizationServerProvider) -> list[BaseRoute]:
    """Owner password login preserving the validated authorization request."""

    async def login_endpoint(request: Request) -> Any:
        if request.method == "GET":
            params = {name: request.query_params.get(name, "") for name in LOGIN_FORM_FIELDS}
            try:
                await validate_login_request(provider, params)
            except LoginRequestError as failure:
                return JSONResponse({"error": failure.error, "error_description": failure.description}, status_code=400)
            return HTMLResponse(render_login_form(params))

        form = await request.form()
        params = {name: str(form.get(name, "")) for name in LOGIN_FORM_FIELDS}
        client_ip = _client_ip(request)
        retry_after = _throttler.retry_after(client_ip)
        if retry_after > 0:
            return HTMLResponse(
                render_login_form(params, error=f"Too many attempts; retry in {int(retry_after) + 1}s."),
                status_code=429,
                headers={"Retry-After": str(int(retry_after) + 1)},
            )
        try:
            client, redirect_uri, challenge, scopes, resource = await validate_login_request(provider, params)
        except LoginRequestError as failure:
            return JSONResponse({"error": failure.error, "error_description": failure.description}, status_code=400)
        if not verify_password(str(form.get("password", ""))):
            _throttler.record_failure(client_ip)
            return HTMLResponse(render_login_form(params, error="Invalid credentials."), status_code=401)
        _throttler.record_success(client_ip)
        code = provider.issue_authorization_code(client, redirect_uri, challenge, scopes, resource)
        extras = {"state": params["state"]} if params.get("state") else {}
        return RedirectResponse(construct_redirect_uri(str(redirect_uri), code=code.code, **extras), status_code=302)

    return [Route(LOGIN_PATH, login_endpoint, methods=["GET", "POST"])]


def _build_resource_bound_token_route(provider: YYAuthorizationServerProvider) -> Route:
    """SDK /token endpoint composed with the RFC 8707 resource-equality guard.

    The SDK ``TokenHandler`` owns client authentication, redirect binding, and
    PKCE; the guard only compares the token request's ``resource`` against the
    one bound to the authorization code before the exchange runs.
    """
    from mcp.server.auth.handlers.token import TokenHandler
    from mcp.server.auth.middleware.client_auth import ClientAuthenticator
    from mcp.server.auth.routes import _body_limited, _cors, request_response

    handler = TokenHandler(provider, ClientAuthenticator(provider))

    async def token_endpoint(request: Request) -> Any:
        if request.method == "POST":
            form = await request.form()
            code = form.get("code")
            resource = form.get("resource")
            if isinstance(code, str) and not provider.token_request_resource_matches(
                code, resource if isinstance(resource, str) else None
            ):
                return JSONResponse(
                    {"error": "invalid_grant", "error_description": "resource does not match the authorization request."},
                    status_code=400,
                    headers={"Cache-Control": "no-store"},
                )
        return await handler.handle(request)

    # Mirror create_auth_routes' /token composition exactly, with the guard added.
    endpoint = _cors(_body_limited(request_response(token_endpoint)), ["POST", "OPTIONS"])
    return Route(TOKEN_PATH, endpoint=endpoint, methods=["POST", "OPTIONS"])


