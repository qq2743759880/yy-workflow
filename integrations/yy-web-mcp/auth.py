    if not _auth_secret:
        raise RuntimeError("auth.configure_auth() must run before build_oauth_stack().")
    issuer_url = AnyHttpUrl((_auth_issuer or issuer or "http://127.0.0.1").rstrip("/"))
    issuer_text = str(issuer_url)  # canonical spelling used by metadata and tokens
    signing_key = derive_jwt_key(high_entropy_material=_auth_secret, salt=issuer_text)
    token_issuer = JWTIssuer(issuer=issuer_text, audience=issuer_text, signing_key=signing_key)
    verifier = YYTokenVerifier(signing_key=signing_key, issuer=issuer_text, resource=issuer_text)
    client_manager = CIMDClientManager(
        enable_cimd=True,
        default_scope=PRODUCTION_SCOPE,
        allowed_redirect_uri_patterns=None,  # per-document allowlists (CIMD) / registered URIs (DCR)
    )
    provider = YYAuthorizationServerProvider(
        client_manager=client_manager, token_issuer=token_issuer, verifier=verifier, resource=issuer_text
    )

    remote_provider = RemoteAuthProvider(
        token_verifier=verifier,
        authorization_servers=[issuer_url],
        base_url=issuer_url,
        scopes_supported=[PRODUCTION_SCOPE],
    )

    as_routes = [
        route
        for route in create_auth_routes(
            provider,
            issuer_url,
            client_registration_options=ClientRegistrationOptions(
                enabled=True,
                valid_scopes=list(SUPPORTED_SCOPES),
                default_scopes=[PRODUCTION_SCOPE],
            ),
        )
        if getattr(route, "path", None) != TOKEN_PATH  # replaced below with the resource-bound one
    ]
    routes: list[BaseRoute] = [
        *remote_provider.get_routes(),  # RFC 9728 /.well-known/oauth-protected-resource
        *as_routes,
        _build_resource_bound_token_route(provider),
        *build_login_routes(provider),
    ]
    metadata_url = f"{issuer_text.rstrip('/')}{WELL_KNOWN_PROTECTED_RESOURCE}"
    middleware = [Middleware(BearerChallengeMiddleware, verifier=verifier, resource_metadata_url=metadata_url)]
    return OAuthAssembly(
        provider=provider,
        verifier=verifier,
        remote_provider=remote_provider,
        routes=routes,
        middleware=middleware,
        issuer=issuer_text,
        resource=issuer_text,
        metadata_url=metadata_url,
    )
